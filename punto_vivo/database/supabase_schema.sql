create index if not exists idx_visits_created  on public.visits(created_at desc);
create index if not exists idx_visits_customer on public.visits(customer_id, visit_number);
create index if not exists idx_visits_phone    on public.visits(phone);
create index if not exists idx_visits_token    on public.visits(request_token);
create index if not exists idx_products_cat    on public.products(category_id, sort_order, id);
create index if not exists idx_rate_events     on public.rate_events(scope, key_hash, created_epoch);

