create extension if not exists pgcrypto;

-- ---------------------------------------------------------------- tablas ----
create table if not exists public.customers (
  id         bigint generated by default as identity primary key,
  full_name  text not null check (char_length(full_name) between 3 and 100),
  phone      text not null unique check (phone ~ '^[0-9]{10}$'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.visits (
  id            bigint generated by default as identity primary key,
  customer_id   bigint not null references public.customers(id) on delete restrict,
  visit_number  integer not null check (visit_number > 0),
  full_name     text not null,
  phone         text not null check (char_length(phone) = 10),
  visit_date    date not null default (now() at time zone 'America/Santo_Domingo')::date,
  visit_time    time not null default (now() at time zone 'America/Santo_Domingo')::time,
  created_at    timestamptz not null default now(),
  created_epoch double precision not null default extract(epoch from now()),
  request_token text not null unique,
  ip_hash       text,
  unique (customer_id, visit_number)
);

create table if not exists public.categories (
  id          bigint generated by default as identity primary key,
  name        text not null unique,
  description text not null default '',
  image       text not null default '',
  sort_order  integer not null default 0,
  active      boolean not null default true
);

create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  category_id bigint not null references public.categories(id) on delete restrict,
  name        text not null,
  description text not null default '',
  price       numeric(10,2) not null default 0 check (price >= 0),
  image       text not null default '',
  available   boolean not null default true,
  is_demo     boolean not null default true,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.admins (
  id            bigint generated by default as identity primary key,
  email         text not null unique,
  password_hash text not null,
  role          text not null default 'admin' check (role in ('admin','superadmin')),
  created_at    timestamptz not null default now()
);

create table if not exists public.admin_sessions (
  token_hash text primary key,
  admin_id   bigint not null references public.admins(id) on delete cascade,
  csrf_token text not null,
  created_at double precision not null,
  expires_at double precision not null
);

create table if not exists public.rate_events (
  id            bigint generated by default as identity primary key,
  scope         text not null,
  key_hash      text not null,
  created_epoch double precision not null
);

-- Evita que dos funciones frías de Vercel siembren el menú demo a la vez.
create table if not exists public.pv_meta (
  key         text primary key,
  value       text,
  created_at  timestamptz not null default now()
);

create index if not exists idx_visits_created  on public.visits(created_at desc);
create index if not exists idx_visits_customer on public.visits(customer_id, visit_number);
create index if not exists idx_visits_phone    on public.visits(phone);
create index if not exists idx_visits_token    on public.visits(request_token);
create index if not exists idx_products_cat    on public.products(category_id, sort_order, id);
create index if not exists idx_rate_events     on public.rate_events(scope, key_hash, created_epoch);

