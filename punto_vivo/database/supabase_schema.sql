-- ------------------------------------------------- registro atómico --------
-- Misma regla de negocio que visits.py: idempotencia por request_token y
-- ventana de 20 s para evitar visitas accidentales repetidas por doble clic.
create or replace function public.registrar_visita(
  p_nombre text,
  p_telefono text,
  p_token text,
  p_ip_hash text default null,
  p_created_epoch double precision default null
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_customer bigint;
  v_visit bigint;
  v_num integer;
  v_existing jsonb;
  v_epoch double precision := coalesce(p_created_epoch, extract(epoch from now()));
  v_now timestamptz := to_timestamp(v_epoch);
  v_date date := (v_now at time zone 'America/Santo_Domingo')::date;
  v_time time := (v_now at time zone 'America/Santo_Domingo')::time;
begin
  if p_nombre is null or char_length(trim(p_nombre)) < 3
     or p_telefono !~ '^[0-9]{10}$' or p_token is null then
    raise exception 'Datos de registro inválidos';
  end if;

  select jsonb_build_object(
    'visit_id', id, 'visit_number', visit_number, 'full_name', full_name,
    'phone', phone, 'visit_date', visit_date, 'visit_time', visit_time,
    'created_at', created_at, 'duplicate', true
  ) into v_existing from public.visits where request_token = p_token;

  if found then
    return v_existing;
  end if;

  perform pg_advisory_xact_lock(hashtext(p_telefono));

  select jsonb_build_object(
    'visit_id', id, 'visit_number', visit_number, 'full_name', full_name,
    'phone', phone, 'visit_date', visit_date, 'visit_time', visit_time,
    'created_at', created_at, 'duplicate', true
  ) into v_existing
  from public.visits
  where phone = p_telefono and v_epoch - created_epoch < 20
  order by id desc limit 1;

  if found then
    return v_existing;
  end if;

  insert into public.customers(full_name, phone, created_at, updated_at)
  values (trim(p_nombre), p_telefono, v_now, v_now)
  on conflict (phone) do update set full_name = excluded.full_name, updated_at = excluded.updated_at
  returning id into v_customer;

  select count(*) + 1 into v_num from public.visits where customer_id = v_customer;

  insert into public.visits(customer_id, visit_number, full_name, phone, visit_date,
                            visit_time, created_at, created_epoch, request_token, ip_hash)
  values (v_customer, v_num, trim(p_nombre), p_telefono, v_date, v_time,
          v_now, v_epoch, p_token, p_ip_hash)
  returning id into v_visit;

  return jsonb_build_object(
    'visit_id', v_visit, 'visit_number', v_num, 'full_name', trim(p_nombre),
    'phone', p_telefono, 'visit_date', v_date, 'visit_time', v_time,
    'created_at', v_now, 'duplicate', false
  );
end;
$$;

revoke all on function public.registrar_visita(text, text, text, text, double precision) from public;
grant execute on function public.registrar_visita(text, text, text, text, double precision) to service_role;

-- ------------------------------------------------ anti-abuso atómico --------
create or replace function public.pv_allow_event(
  p_scope text,
  p_key_hash text,
  p_created_epoch double precision,
  p_max integer,
  p_cutoff double precision
) returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  n integer;
begin
  delete from public.rate_events where created_epoch < p_cutoff - 3600;
  select count(*) into n
  from public.rate_events
  where scope = p_scope and key_hash = p_key_hash and created_epoch > p_cutoff;
  if n >= p_max then
    return false;
  end if;
  insert into public.rate_events(scope, key_hash, created_epoch)
  values (p_scope, p_key_hash, p_created_epoch);
  return true;
end;
$$;

revoke all on function public.pv_allow_event(text, text, double precision, integer, double precision) from public;
grant execute on function public.pv_allow_event(text, text, double precision, integer, double precision) to service_role;

