-- Creación atómica del pedido: el cliente nunca envía su customer_id ni precios.
create or replace function public.crear_pedido(
  p_visit_id bigint,
  p_items jsonb,
  p_idempotencia_key text,
  p_delivery_method text default 'retiro',
  p_address jsonb default null,
  p_notes text default '',
  p_payment_method text default 'efectivo'
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_customer bigint;
  v_visit record;
  v_cliente record;
  v_order bigint;
  v_item jsonb;
  v_prod record;
  v_address bigint;
  v_sub numeric(12,2) := 0;
  v_line numeric(12,2);
  v_cant integer;
  v_qty integer;
  v_sort integer := 0;
  v_existing jsonb;
  v_number text;
begin
  select * into v_visit from public.visits where id = p_visit_id;
  if not found then raise exception 'Visita no válida'; end if;
  select * into v_cliente from public.customers where id = v_visit.customer_id;
  if not found then raise exception 'Cliente no encontrado'; end if;
  v_customer := v_cliente.id;

  perform pg_advisory_xact_lock(hashtext(p_idempotencia_key));
  select jsonb_build_object(
    'order_id', id, 'order_number', order_number, 'total', total, 'duplicate', true
  ) into v_existing from public.orders where idempotency_key = p_idempotencia_key;
  if found then return v_existing; end if;

  v_cant := jsonb_array_length(coalesce(p_items, '[]'::jsonb));
  if v_cant < 1 or v_cant > 50 then raise exception 'Pedido sin artículos o demasiados artículos'; end if;
  if p_delivery_method not in ('delivery','retiro') then raise exception 'Entrega no válida'; end if;
  if p_payment_method not in ('efectivo','tarjeta','transferencia') then raise exception 'Pago no válido'; end if;

  if p_delivery_method = 'delivery' then
    if p_address is null or nullif(trim(coalesce(p_address->>'address_line1','')), '') is null then
      raise exception 'La dirección de entrega es obligatoria';
    end if;
    insert into public.delivery_addresses(customer_id, address_line1, address_line2, city, province, notes)
    values (v_customer, p_address->>'address_line1', coalesce(p_address->>'address_line2',''),
            coalesce(p_address->>'city',''), coalesce(p_address->>'province',''),
            coalesce(p_address->>'notes',''))
    returning id into v_address;
  end if;

  insert into public.orders(customer_id, visit_id, delivery_address_id, order_number,
                            delivery_method, customer_name_snapshot, customer_phone_snapshot,
                            notes, idempotency_key)
  values (v_customer, p_visit_id, v_address, 'TEMP-' || p_idempotencia_key,
          p_delivery_method, v_cliente.full_name, v_cliente.phone,
          coalesce(p_notes,''), p_idempotencia_key)
  returning id into v_order;

  for v_item in select value from jsonb_array_elements(p_items) loop
    select id, name, price into v_prod
    from public.products
    where id = (v_item->>'product_id')::bigint
      and available
      and category_id in (select id from public.categories where active);
    if not found or v_prod.price is null or v_prod.price <= 0 then
      raise exception 'Producto no disponible o precio por definir';
    end if;
    v_qty := (v_item->>'quantity')::integer;
    if v_qty is null or v_qty not between 1 and 99 then raise exception 'Cantidad no válida'; end if;
    v_line := round(v_prod.price * v_qty, 2);
    insert into public.order_items(order_id, product_id, product_name_snapshot,
                                   unit_price, quantity, notes, line_total, sort_order)
    values (v_order, v_prod.id, v_prod.name, v_prod.price, v_qty,
            coalesce(v_item->>'notes',''), v_line, v_sort);
    v_sub := v_sub + v_line;
    v_sort := v_sort + 1;
  end loop;

  v_number := 'PV-' || to_char(now() at time zone 'America/Santo_Domingo', 'YYYYMMDD')
              || '-' || lpad(v_order::text, 6, '0');
  update public.orders
     set order_number = v_number, subtotal = v_sub, total = v_sub, updated_at = now()
   where id = v_order;

  insert into public.payments(order_id, method, status, amount)
  values (v_order, p_payment_method, 'pendiente', v_sub);

  return jsonb_build_object(
    'order_id', v_order, 'order_number', v_number, 'total', v_sub, 'duplicate', false
  );
end;
$$;

revoke all on function public.crear_pedido(bigint, jsonb, text, text, jsonb, text, text) from public;
grant execute on function public.crear_pedido(bigint, jsonb, text, text, jsonb, text, text) to service_role;
