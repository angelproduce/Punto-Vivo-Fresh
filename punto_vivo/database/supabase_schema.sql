create table if not exists public.delivery_addresses (
  id            bigint generated by default as identity primary key,
  customer_id   bigint not null references public.customers(id) on delete restrict,
  address_line1 text not null check (char_length(trim(address_line1)) between 4 and 200),
  address_line2 text not null default '',
  city          text not null default '',
  province      text not null default '',
  notes         text not null default '',
  created_at    timestamptz not null default now()
);

create table if not exists public.orders (
  id                       bigint generated by default as identity primary key,
  customer_id              bigint not null references public.customers(id) on delete restrict,
  visit_id                 bigint references public.visits(id) on delete set null,
  delivery_address_id      bigint references public.delivery_addresses(id) on delete set null,
  order_number             text not null unique,
  status                   text not null default 'pendiente'
    check (status in ('pendiente','aceptada','preparando','lista','entregada','rechazada','cancelada')),
  delivery_method          text not null default 'retiro'
    check (delivery_method in ('delivery','retiro')),
  customer_name_snapshot   text not null,
  customer_phone_snapshot  text not null check (customer_phone_snapshot ~ '^[0-9]{10}$'),
  notes                    text not null default '',
  subtotal                 numeric(12,2) not null default 0 check (subtotal >= 0),
  discount                 numeric(12,2) not null default 0 check (discount >= 0),
  delivery_fee             numeric(12,2) not null default 0 check (delivery_fee >= 0),
  total                    numeric(12,2) not null default 0 check (total >= 0),
  idempotency_key          text not null unique,
  created_at               timestamptz not null default now(),
  updated_at               timestamptz not null default now()
);

create table if not exists public.order_items (
  id                    bigint generated by default as identity primary key,
  order_id              bigint not null references public.orders(id) on delete cascade,
  product_id            bigint not null references public.products(id) on delete restrict,
  product_name_snapshot text not null,
  unit_price            numeric(12,2) not null check (unit_price > 0),
  quantity              integer not null check (quantity between 1 and 99),
  notes                 text not null default '',
  line_total            numeric(12,2) not null check (line_total >= 0),
  sort_order            integer not null default 0
);

create table if not exists public.payments (
  id                  bigint generated by default as identity primary key,
  order_id            bigint not null references public.orders(id) on delete cascade,
  method              text not null check (method in ('efectivo','tarjeta','transferencia')),
  status              text not null default 'pendiente'
    check (status in ('pendiente','aprobado','rechazado','reembolsado')),
  amount              numeric(12,2) not null check (amount >= 0),
  provider            text not null default '',
  provider_payment_id text not null default '',
  paid_at             timestamptz,
  created_at          timestamptz not null default now()
);

create index if not exists idx_orders_customer on public.orders(customer_id, created_at desc);
